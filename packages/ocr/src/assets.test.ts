// @vitest-environment node
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { OCR_ASSET_FILES, resolveAssetUrls } from './assets';

const root = process.cwd();
const manifest = JSON.parse(
  readFileSync(join(root, 'packages', 'ocr', 'assets.manifest.json'), 'utf8'),
) as { files: { name: string; bytes: number; sha256: string }[] };

describe('asset manifest', () => {
  it('lists exactly the files the engine loads', () => {
    expect(manifest.files.map((f) => f.name).sort()).toEqual(Object.values(OCR_ASSET_FILES).sort());
  });

  it('records a sha-256 and size for every file', () => {
    for (const file of manifest.files) {
      expect(file.sha256).toMatch(/^[0-9a-f]{64}$/);
      expect(file.bytes).toBeGreaterThan(10_000);
    }
  });

  // The assets are generated by scripts/copy-ocr-assets.mjs; when they exist they must match the
  // manifest exactly (a stale or hand-edited public/ocr must not slip into a build unnoticed).
  const generated = join(root, 'public', 'ocr');
  it.skipIf(!existsSync(generated))('generated public/ocr matches the recorded hashes', () => {
    for (const file of manifest.files) {
      const path = join(generated, file.name);
      expect(statSync(path).size).toBe(file.bytes);
      expect(createHash('sha256').update(readFileSync(path)).digest('hex')).toBe(file.sha256);
    }
  });
});

describe('resolveAssetUrls', () => {
  it('derives every path from the one base', () => {
    expect(resolveAssetUrls('chrome-extension://id/ocr/')).toEqual({
      base: 'chrome-extension://id/ocr/',
      workerPath: 'chrome-extension://id/ocr/worker.min.js',
      corePath: 'chrome-extension://id/ocr/tesseract-core-simd-lstm.js',
      langPath: 'chrome-extension://id/ocr',
    });
  });

  it('accepts moz-extension and loopback http, refuses the rest', () => {
    expect(() => resolveAssetUrls('moz-extension://id/ocr/')).not.toThrow();
    expect(() => resolveAssetUrls('http://localhost:3000/ocr/')).not.toThrow();
    expect(() => resolveAssetUrls('https://localhost/ocr/')).toThrow(TypeError);
    expect(() => resolveAssetUrls('file:///ocr/')).toThrow(TypeError);
    expect(() => resolveAssetUrls('data:text/plain,x')).toThrow(TypeError);
    expect(() => resolveAssetUrls('chrome-extension://user:pw@id/ocr/')).toThrow(TypeError);
  });
});
